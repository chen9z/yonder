//! `yonder bot sync`: a persistent bot's rules go to where it works, its
//! memory comes back.
//!
//! - Push: `<cwd>/AGENTS.md` becomes `bots/<name>/AGENTS.md`, a blank
//!   line, `MARK`, a blank line and the manual. Not over a file changed
//!   there since: one that is neither what was last pushed (its hash is in
//!   the ledger) nor what would be pushed now is `Drifted` and left alone,
//!   unless forced.
//! - Pull: `<cwd>/MEMORY.md`, when it differs, replaces
//!   `bots/<name>/MEMORY.md` (a new file renamed over it).
//!
//! Nothing is deleted, and nothing but `AGENTS.md` is written where the
//! bot works. Locally no symbolic link is followed; on another machine
//! files go through hc (`crate::hc::HcFiles`).

use std::ffi::OsString;
use std::io::{Read, Write};
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::sync::atomic::AtomicBool;

use sha2::{Digest, Sha256};
use yonder_model::BotDef;

use crate::check_exec::hex;
use crate::hc::HcFiles;

/// The line between a bot's own rules and the manual.
pub const MARK: &str = "<!-- yonder manual: generated by yonder bot sync; edits below are overwritten -->";

/// Files where a bot works, by name (`AGENTS.md`, `MEMORY.md`).
pub trait Files {
    /// The file, or None if there is none.
    fn read(&mut self, name: &str) -> Result<Option<Vec<u8>>, String>;
    fn write(&mut self, name: &str, data: &[u8]) -> Result<(), String>;
}

/// A directory on this computer.
pub struct LocalFiles(pub PathBuf);

impl Files for LocalFiles {
    fn read(&mut self, name: &str) -> Result<Option<Vec<u8>>, String> {
        read_file(&self.0.join(name))
    }

    fn write(&mut self, name: &str, data: &[u8]) -> Result<(), String> {
        let path = self.0.join(name);
        let mut file = std::fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK)
            .open(&path)
            .map_err(|e| not_followed(&path, e))?;
        file.write_all(data).map_err(|e| format!("{}: {e}", path.display()))
    }
}

/// The regular file at `path`, None if nothing is there; a symbolic link
/// is not followed, and anything else is not read.
fn read_file(path: &Path) -> Result<Option<Vec<u8>>, String> {
    // Without O_NONBLOCK, opening a FIFO would wait for a writer.
    let opened = std::fs::OpenOptions::new().read(true).custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK).open(path);
    let mut file = match opened {
        Ok(file) => file,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(not_followed(path, e)),
    };
    let what = |e: std::io::Error| format!("{}: {e}", path.display());
    if !file.metadata().map_err(what)?.is_file() {
        return Err(format!("{} is not a regular file", path.display()));
    }
    let mut data = Vec::new();
    file.read_to_end(&mut data).map_err(what)?;
    Ok(Some(data))
}

fn not_followed(path: &Path, e: std::io::Error) -> String {
    if e.raw_os_error() == Some(libc::ELOOP) {
        format!("{} is a symbolic link; it is not followed", path.display())
    } else {
        format!("{}: {e}", path.display())
    }
}

/// `data` as the file at `path`: written to a new file beside it, then
/// renamed over it, so the file is always whole.
fn replace(path: &Path, data: &[u8]) -> Result<(), String> {
    let name = path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let tmp = path.with_file_name(format!(".{name}.{}.yonder-new", std::process::id()));
    let what = |e: std::io::Error| format!("{}: {e}", tmp.display());
    let written = (|| {
        let mut file = std::fs::OpenOptions::new().write(true).create_new(true).mode(0o644).open(&tmp)?;
        file.write_all(data)?;
        file.sync_all()?;
        std::fs::rename(&tmp, path)
    })();
    if let Err(e) = written {
        // Ours, made just now.
        let _ = std::fs::remove_file(&tmp);
        return Err(what(e));
    }
    Ok(())
}

/// The AGENTS.md pushed for a bot's own `rules`.
pub fn agents_md(rules: &[u8], manual: &str) -> Vec<u8> {
    let mut text = rules.to_vec();
    if !text.is_empty() && !text.ends_with(b"\n") {
        text.push(b'\n');
    }
    text.extend_from_slice(format!("\n{MARK}\n\n{manual}").as_bytes());
    text
}

pub fn sha256(data: &[u8]) -> String {
    hex(&Sha256::digest(data))
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Push {
    Pushed,
    Unchanged,
    Drifted,
    Skipped,
    Failed,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Pull {
    Pulled,
    Unchanged,
    Missing,
    Failed,
}

impl Push {
    pub fn as_str(self) -> &'static str {
        match self {
            Push::Pushed => "pushed",
            Push::Unchanged => "unchanged",
            Push::Drifted => "drifted",
            Push::Skipped => "skipped",
            Push::Failed => "failed",
        }
    }
}

impl Pull {
    pub fn as_str(self) -> &'static str {
        match self {
            Pull::Pulled => "pulled",
            Pull::Unchanged => "unchanged",
            Pull::Missing => "missing",
            Pull::Failed => "failed",
        }
    }
}

/// How one bot's sync went (or, dry, would go).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Synced {
    pub push: Push,
    pub pull: Pull,
    /// Why what failed did.
    pub why: Vec<String>,
    /// The hash of the AGENTS.md now there, for the ledger, when it is not
    /// the one recorded.
    pub record: Option<String>,
}

impl Synced {
    /// `<bot>: AGENTS.md <push>; MEMORY.md <pull>`, and ` — <why>` on failure.
    pub fn line(&self, bot: &str) -> String {
        let mut line = format!("{bot}: AGENTS.md {}; MEMORY.md {}", self.push.as_str(), self.pull.as_str());
        if !self.why.is_empty() {
            line += &format!(" — {}", self.why.join("; "));
        }
        line
    }

    /// Nothing drifted or failed.
    pub fn complete(&self) -> bool {
        !matches!(self.push, Push::Drifted | Push::Failed) && self.pull != Pull::Failed
    }

    pub fn failed(why: String) -> Synced {
        Synced { push: Push::Failed, pull: Pull::Failed, why: vec![why], record: None }
    }
}

#[derive(Clone, Copy, Debug, Default)]
pub struct Options {
    /// Write over an AGENTS.md changed there.
    pub force: bool,
    /// Read and tell, write nothing.
    pub dry_run: bool,
}

/// Where a bot's files are kept in the ledger: `<machine>:<cwd>`.
pub fn target(def: &BotDef) -> String {
    format!("{}:{}", def.machine, def.cwd.as_deref().unwrap_or(""))
}

/// The files where the bot `def` works: on this computer (`~/` from
/// `home`, the user's), or through hc `bin` on another machine (`~/`
/// dropped: hc starts a relative path there from that machine's home).
pub fn files_of(def: &BotDef, home: Option<OsString>, bin: &Path, stop: &'static AtomicBool) -> Result<Box<dyn Files>, String> {
    let cwd = def.cwd.as_deref().ok_or("it has no cwd")?;
    if def.machine == "local" {
        let dir = match cwd.strip_prefix("~/") {
            Some(rest) => {
                let home = home.filter(|h| !h.is_empty()).ok_or("cwd is under ~/, and HOME is not set")?;
                Path::new(&home).join(rest)
            }
            None => cwd.into(),
        };
        return Ok(Box::new(LocalFiles(dir)));
    }
    let dir = cwd.strip_prefix("~/").unwrap_or(cwd).to_string();
    Ok(Box::new(HcFiles { bin: bin.into(), machine: def.machine.clone(), dir, stop }))
}

/// Pushes the bot in `bot_dir`'s AGENTS.md to `there`, with `manual` at its
/// end, and pulls its MEMORY.md back. `last` is the hash of what was last
/// pushed there.
pub fn sync(bot_dir: &Path, there: &mut dyn Files, manual: &str, last: Option<&str>, opts: Options) -> Synced {
    let mut why = Vec::new();
    let (push, record) = push(bot_dir, there, manual, last, opts).unwrap_or_else(|e| {
        why.push(e);
        (Push::Failed, None)
    });
    let pull = pull(bot_dir, there, opts).unwrap_or_else(|e| {
        why.push(e);
        Pull::Failed
    });
    Synced { push, pull, why, record }
}

fn push(bot_dir: &Path, there: &mut dyn Files, manual: &str, last: Option<&str>, opts: Options) -> Result<(Push, Option<String>), String> {
    let Some(rules) = read_file(&bot_dir.join("AGENTS.md"))? else {
        return Ok((Push::Skipped, None));
    };
    let new = agents_md(&rules, manual);
    let hash = sha256(&new);
    let now = there.read("AGENTS.md")?;
    let record = (last != Some(hash.as_str())).then(|| hash.clone());
    match now {
        Some(now) if now == new => return Ok((Push::Unchanged, record)),
        Some(now) if last != Some(sha256(&now).as_str()) && !opts.force => return Ok((Push::Drifted, None)),
        _ => {}
    }
    if !opts.dry_run {
        there.write("AGENTS.md", &new)?;
    }
    Ok((Push::Pushed, record))
}

fn pull(bot_dir: &Path, there: &mut dyn Files, opts: Options) -> Result<Pull, String> {
    let Some(memory) = there.read("MEMORY.md")? else {
        return Ok(Pull::Missing);
    };
    let path = bot_dir.join("MEMORY.md");
    if read_file(&path)?.is_some_and(|ours| ours == memory) {
        return Ok(Pull::Unchanged);
    }
    if !opts.dry_run {
        replace(&path, &memory)?;
    }
    Ok(Pull::Pulled)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeMap;

    /// Files kept in memory, or failing.
    #[derive(Default)]
    struct Fake {
        files: BTreeMap<String, Vec<u8>>,
        writes: usize,
        broken: bool,
    }

    impl Files for Fake {
        fn read(&mut self, name: &str) -> Result<Option<Vec<u8>>, String> {
            if self.broken {
                return Err("hc file read: exit:4: machine_unknown".into());
            }
            Ok(self.files.get(name).cloned())
        }

        fn write(&mut self, name: &str, data: &[u8]) -> Result<(), String> {
            self.writes += 1;
            self.files.insert(name.into(), data.to_vec());
            Ok(())
        }
    }

    const MANUAL: &str = "manual line\n";
    const RUN: Options = Options { force: false, dry_run: false };

    fn bot(name: &str, rules: Option<&str>) -> PathBuf {
        let dir = crate::test_dir(name);
        if let Some(rules) = rules {
            std::fs::write(dir.join("AGENTS.md"), rules).unwrap();
        }
        dir
    }

    #[test]
    fn pushes_the_rules_and_the_manual() {
        assert_eq!(agents_md(b"rules\n", MANUAL), format!("rules\n\n{MARK}\n\nmanual line\n").into_bytes());
        assert_eq!(agents_md(b"rules", MANUAL), agents_md(b"rules\n", MANUAL));
        assert_eq!(agents_md(b"", MANUAL), format!("\n{MARK}\n\nmanual line\n").into_bytes());

        let dir = bot("sync-push", Some("rules\n"));
        let mut there = Fake::default();
        let first = sync(&dir, &mut there, MANUAL, None, RUN);
        let hash = sha256(&agents_md(b"rules\n", MANUAL));
        assert_eq!(first, Synced { push: Push::Pushed, pull: Pull::Missing, why: vec![], record: Some(hash.clone()) });
        assert_eq!(first.line("ops"), "ops: AGENTS.md pushed; MEMORY.md missing");
        assert_eq!(there.files["AGENTS.md"], agents_md(b"rules\n", MANUAL));
        let again = sync(&dir, &mut there, MANUAL, Some(&hash), RUN);
        assert_eq!((again.push, again.record, there.writes), (Push::Unchanged, None, 1));
        // The same text there with no record: unchanged, and recorded.
        let unrecorded = sync(&dir, &mut there, MANUAL, None, RUN);
        assert_eq!((unrecorded.push, unrecorded.record), (Push::Unchanged, Some(hash.clone())));
        // Rules changed here: what is there is what was pushed, so it goes.
        std::fs::write(dir.join("AGENTS.md"), "rules v2\n").unwrap();
        assert_eq!(sync(&dir, &mut there, MANUAL, Some(&hash), RUN).push, Push::Pushed);
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn never_writes_over_a_change_made_there() {
        let dir = bot("sync-drift", Some("rules\n"));
        let mut there = Fake::default();
        let hash = sync(&dir, &mut there, MANUAL, None, RUN).record.unwrap();
        there.files.get_mut("AGENTS.md").unwrap().extend_from_slice(b"hand edit\n");
        let drifted = sync(&dir, &mut there, MANUAL, Some(&hash), RUN);
        assert_eq!((drifted.push, drifted.record.clone(), drifted.complete()), (Push::Drifted, None, false));
        assert!(there.files["AGENTS.md"].ends_with(b"hand edit\n"));
        // A file there before the first sync is not Yonder's either.
        let mut fresh = Fake::default();
        fresh.files.insert("AGENTS.md".into(), b"someone's\n".to_vec());
        assert_eq!(sync(&dir, &mut fresh, MANUAL, None, RUN).push, Push::Drifted);
        assert_eq!(fresh.writes, 0);
        let forced = sync(&dir, &mut there, MANUAL, Some(&hash), Options { force: true, dry_run: false });
        // What it wrote is what the ledger has already.
        assert_eq!((forced.push, forced.record), (Push::Pushed, None));
        assert_eq!(there.files["AGENTS.md"], agents_md(b"rules\n", MANUAL));
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn pulls_memory_back_and_keeps_it() {
        let dir = bot("sync-pull", None);
        let mut there = Fake::default();
        // No rules here: nothing pushed, nothing written there.
        assert_eq!(sync(&dir, &mut there, MANUAL, None, RUN).line("ops"), "ops: AGENTS.md skipped; MEMORY.md missing");
        there.files.insert("MEMORY.md".into(), b"m1\n".to_vec());
        assert_eq!(sync(&dir, &mut there, MANUAL, None, RUN).pull, Pull::Pulled);
        assert_eq!(std::fs::read(dir.join("MEMORY.md")).unwrap(), b"m1\n");
        assert_eq!(sync(&dir, &mut there, MANUAL, None, RUN).pull, Pull::Unchanged);
        there.files.clear();
        assert_eq!(sync(&dir, &mut there, MANUAL, None, RUN).pull, Pull::Missing);
        assert_eq!(std::fs::read(dir.join("MEMORY.md")).unwrap(), b"m1\n");
        // Only MEMORY.md is left in the bot's directory: no temporary file.
        let names: Vec<_> = std::fs::read_dir(&dir).unwrap().map(|e| e.unwrap().file_name()).collect();
        assert_eq!(names, ["MEMORY.md"]);
        assert_eq!(there.writes, 0);
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn a_dry_run_writes_nothing() {
        let dir = bot("sync-dry", Some("rules\n"));
        let mut there = Fake::default();
        there.files.insert("MEMORY.md".into(), b"m1\n".to_vec());
        let dry = Options { force: true, dry_run: true };
        let said = sync(&dir, &mut there, MANUAL, None, dry);
        assert_eq!((said.push, said.pull), (Push::Pushed, Pull::Pulled));
        assert_eq!((there.writes, there.files.len()), (0, 1));
        assert!(!dir.join("MEMORY.md").exists());
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn failures_are_told_and_others_go_on() {
        let dir = bot("sync-fail", Some("rules\n"));
        let mut there = Fake { broken: true, ..Fake::default() };
        let said = sync(&dir, &mut there, MANUAL, None, RUN);
        assert_eq!(said.line("trainer"), "trainer: AGENTS.md failed; MEMORY.md failed — hc file read: exit:4: machine_unknown; hc file read: exit:4: machine_unknown");
        assert!(!said.complete());
        // Its own MEMORY.md a link: the pull fails, the push still goes.
        let mut there = Fake::default();
        there.files.insert("MEMORY.md".into(), b"m1\n".to_vec());
        std::os::unix::fs::symlink("/tmp/example/elsewhere", dir.join("MEMORY.md")).unwrap();
        let said = sync(&dir, &mut there, MANUAL, None, RUN);
        assert_eq!((said.push, said.pull), (Push::Pushed, Pull::Failed));
        assert!(said.why[0].ends_with("MEMORY.md is a symbolic link; it is not followed"), "{:?}", said.why);
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn local_files_are_never_followed() {
        let dir = crate::test_dir("sync-local");
        let mut files = LocalFiles(dir.clone());
        assert_eq!(files.read("AGENTS.md"), Ok(None));
        files.write("AGENTS.md", b"x").unwrap();
        assert_eq!(files.read("AGENTS.md"), Ok(Some(b"x".to_vec())));
        std::fs::write(dir.join("target"), "someone's").unwrap();
        std::os::unix::fs::symlink(dir.join("target"), dir.join("MEMORY.md")).unwrap();
        assert!(files.read("MEMORY.md").unwrap_err().contains("symbolic link"));
        assert!(files.write("MEMORY.md", b"ours").unwrap_err().contains("symbolic link"));
        assert_eq!(std::fs::read_to_string(dir.join("target")).unwrap(), "someone's");
        std::fs::create_dir(dir.join("sub")).unwrap();
        assert!(LocalFiles(dir.clone()).read("sub").unwrap_err().contains("not a regular file"));
        // No such directory: a failure, and nothing is made.
        assert!(LocalFiles(dir.join("gone")).write("AGENTS.md", b"x").is_err());
        assert!(!dir.join("gone").exists());
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn finds_where_a_bot_works() {
        static NEVER: AtomicBool = AtomicBool::new(false);
        let def = |machine: &str, cwd: &str| BotDef {
            name: "ops".into(),
            description: "x".into(),
            kind: yonder_model::BotKind::Persistent,
            machine: machine.into(),
            cwd: Some(cwd.into()),
            harness: "pi".into(),
            model: None,
            args: vec![],
            memory_id: None,
            env: vec![],
        };
        let home = || Some(OsString::from("/tmp/example"));
        assert_eq!(target(&def("gpu-box", "~/bots/trainer")), "gpu-box:~/bots/trainer");
        assert!(files_of(&def("local", "~/ops"), None, Path::new("hc"), &NEVER).is_err());
        assert!(files_of(&def("local", "~/ops"), home(), Path::new("hc"), &NEVER).is_ok());
        assert!(files_of(&def("gpu-box", "~/ops"), None, Path::new("hc"), &NEVER).is_ok());
    }
}
